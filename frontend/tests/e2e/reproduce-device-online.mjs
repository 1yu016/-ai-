import { chromium } from '@playwright/test'
import { createRequire } from 'node:module'
const requireBackend = createRequire(new URL('../../../backend/package.json', import.meta.url))
const Database = requireBackend('better-sqlite3')
const db = new Database(new URL('../../../backend/data/app.sqlite', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), { readonly: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage()
const rows = () => ({ devices: db.prepare('SELECT id,status,last_online_at FROM device').all(), sessions: db.prepare('SELECT id,device_id,expires_at,last_heartbeat_at,revoked_at FROM device_session ORDER BY id DESC LIMIT 4').all() })
try {
  console.log('BEFORE', JSON.stringify(rows()))
  page.on('response', async response => {
    if (/device-session/.test(response.url())) console.log('NETWORK', response.url(), response.status(), 'device-header-present', !!response.request().headers()['x-device-session'], 'teacher-header-present', !!response.request().headers().authorization, /heartbeat/.test(response.url()) ? await response.text() : '[token redacted]')
  })
  await page.goto('http://localhost:5173/login')
  console.log('LOGIN INPUTS', await page.locator('input').evaluateAll(inputs => inputs.map(input => ({placeholder: input.placeholder, type: input.type}))))
  await page.locator('input').nth(0).fill('teacher_demo')
  await page.locator('input[type=password]').fill('Teacher123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForTimeout(2500)
  console.log('LOGIN URL', page.url())
  await page.goto('http://localhost:5173/classroom/screen/1')
  await page.waitForTimeout(35000)
  console.log('SCREEN URL', page.url(), 'UI', (await page.locator('body').innerText()).slice(0,1600))
  console.log('AFTER', JSON.stringify(rows()))
  const replacement = await browser.newPage()
  await replacement.goto('http://localhost:5173/login')
  await replacement.locator('input').nth(0).fill('teacher_demo')
  await replacement.locator('input[type=password]').fill('Teacher123!')
  await replacement.getByRole('button', { name: '登录', exact: true }).click()
  await replacement.waitForTimeout(1500)
  await replacement.goto('http://localhost:5173/classroom/screen/1')
  await replacement.waitForTimeout(2000)
  await replacement.close()
  await page.reload()
  await page.waitForTimeout(35000)
  console.log('REVOKED RESTORE URL', page.url(), 'UI', (await page.locator('body').innerText()).slice(0,1200))
  console.log('REVOKED RESTORE DB', JSON.stringify(rows()))
} finally { await browser.close(); db.close() }
