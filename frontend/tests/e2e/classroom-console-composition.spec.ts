import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

test('teacher console visual composition at both teaching resolutions', async ({ browser, request }) => {
  test.setTimeout(120000)
  const phase = process.env.CONSOLE_CAPTURE_PHASE === 'before' ? 'before' : 'after'
  const login = await request.post('/auth/login', { data: { account: 'e2e_teacher', password: 'E2eTeacher123!' } })
  expect(login.ok()).toBeTruthy()
  const teacher = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const adminLogin = await request.post('/auth/admin/login', { data: { account: 'e2e_admin', password: 'E2eAdmin123!' } })
  const admin = { Authorization: `Bearer ${(await adminLogin.json()).access_token}` }
  const create = async (url: string, data: Record<string, unknown>) => {
    const response = await request.post(url, { headers: admin, data }); expect(response.ok()).toBeTruthy(); return response.json()
  }
  const group = await create('/classes', { name: '中一班', schoolYear: '2026' })
  const room = await create('/classrooms', { name: '向日葵教室' })
  const device = await create('/devices', { name: '教室大屏', deviceCode: 'CONSOLE-VISUAL', type: 'classroom_screen' })
  const profile = await (await request.get('/auth/profile', { headers: teacher })).json()
  await create(`/classes/${group.id}/teachers`, { teacherId: profile.teacherId, role: 'lead' })
  await create('/device-bindings', { deviceId: device.id, classId: group.id, classroomId: room.id })
  const planResponse = await request.post('/lesson-plans', { headers: teacher, data: { title: '认识数字1', theme: '生活中的数字', ageGroup: '4-5', objectives: '在生活中观察和发现数字1', estimatedMinutes: 20, status: 'ready' } })
  expect(planResponse.ok()).toBeTruthy()
  const plan = await planResponse.json()
  const steps = await request.put(`/lesson-plans/${plan.id}/steps`, { headers: teacher, data: { version: plan.version,
    steps: ['一起找数字', '认识数字1', '找一找', '数字游戏', '分享发现'].map(title => ({ title, stepType: 'teacher_talk', content: '找一找教室里只有一个的物品。', teacherTip: '给小朋友充分的观察时间，鼓励他们说出自己的发现。', durationSeconds: 240 })) } })
  expect(steps.ok()).toBeTruthy()
  const context = await browser.newContext()
  const screen = await context.newPage()
  await screen.goto('/login'); await screen.getByLabel('账号').fill('e2e_teacher'); await screen.getByLabel('密码').fill('E2eTeacher123!')
  await screen.getByRole('button', { name: '登录', exact: true }).click(); await expect(screen).toHaveURL(/my-classes$/)
  await screen.goto(`/classroom/screen/${device.id}`)
  await expect(screen.locator('.status-dot.online')).toBeVisible()
  const started = await request.post('/classroom-runs/start', { headers: teacher, data: { lessonPlanId: plan.id, classId: group.id, classroomId: room.id, deviceId: device.id, requestId: `visual-${Date.now()}` } })
  expect(started.ok()).toBeTruthy()
  const run = await started.json()
  const page = await context.newPage()
  const folder = resolve(import.meta.dirname, '../../../docs/images/classroom-console-composition')
  mkdirSync(folder, { recursive: true })
  for (const [width, height] of [[1440, 900], [1366, 768]]) {
    await page.setViewportSize({ width: width!, height: height! })
    await page.goto(`/classroom/lesson/${run.id}`)
    await expect(page.locator('.live-preview')).toBeVisible()
    await page.waitForTimeout(1800)
    await page.screenshot({ path: resolve(folder, `${phase}-${width}x${height}.png`) })
    console.log('COMPOSITION', width, height, { stage: await page.locator('.live-preview').boundingBox(), viewport: page.viewportSize() })
    if (phase === 'after') {
      const box = await page.locator('.live-preview').boundingBox()
      expect(box).not.toBeNull()
      const areaShare = box!.width * box!.height / (width! * height!)
      expect(areaShare).toBeGreaterThanOrEqual(0.55)
      expect(areaShare).toBeLessThanOrEqual(0.65)
      await expect(page.locator('.center-panel .assistant-panel, .center-panel .director-panel, .center-panel .voice-card')).toHaveCount(0)
      await expect(page.getByText('数字人调试（DEV）')).toHaveCount(0)
      await expect(page.getByRole('button', { name: '调整课堂内容', exact: true })).toBeVisible()
      await expect(page.getByRole('button', { name: '暂停课堂', exact: true })).toBeVisible()
      const stateBefore = await (await request.get(`/classroom-runs/${run.id}`, { headers: teacher })).json()
      await page.getByRole('button', { name: '调整课堂内容', exact: true }).click()
      await expect(page.getByText('当前环节展示队列')).toBeVisible()
      const stateAfter = await (await request.get(`/classroom-runs/${run.id}`, { headers: teacher })).json()
      expect(stateAfter.version).toBe(stateBefore.version)
      expect(stateAfter.playerRecoverySuggestion).toEqual(stateBefore.playerRecoverySuggestion)
      await page.keyboard.press('Escape')
      await page.locator('[data-test="open-interaction"]').click()
      await expect(page.locator('[data-test="fs-interaction"]')).toBeVisible()
      await page.locator('[data-test="fs-close"]').click()
      await expect(page.locator('.live-preview')).toBeVisible()
      await page.locator('[data-test="enter-avatar"]').click()
      await expect(page.locator('[data-test="fs-avatar"]')).toBeVisible()
      await page.locator('[data-test="fs-close"]').click()
      await page.locator('[data-test="open-leaderboard"]').click()
      await expect(page.locator('.fs-body[data-test="fs-leaderboard"]')).toBeVisible()
      await page.locator('[data-test="fs-close"]').click()
      await page.getByRole('button', { name: /^AI教学伙伴/ }).click()
      await expect(page.getByRole('dialog', { name: 'AI教学伙伴' })).toBeVisible()
      await expect.poll(async () => {
        const dialog = await page.getByRole('dialog', { name: 'AI教学伙伴' }).boundingBox()
        return Math.round((dialog?.x ?? width!) + (dialog?.width ?? width!))
      }).toBeLessThanOrEqual(width! + 1)
      await page.screenshot({ path: resolve(folder, `after-${width}x${height}-ai-drawer.png`) })
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: '查看完整教案', exact: true }).click()
      await expect(page.getByRole('dialog', { name: '课堂教案 · 仅教师可见' })).toBeVisible()
      const stateAfterPanels = await (await request.get(`/classroom-runs/${run.id}`, { headers: teacher })).json()
      expect(stateAfterPanels.status).toBe(stateBefore.status)
      expect(stateAfterPanels.version).toBe(stateBefore.version)
      await page.keyboard.press('Escape')
    }
  }
  await context.close()
})
